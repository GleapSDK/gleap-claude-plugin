#!/usr/bin/env node
// Builds plugins/gleap-us/ (the US-region plugin) from the repository root
// (the EU `gleap` plugin). Both plugins share the same skills, hooks and hook
// script; only the names and the MCP URL differ. The copy is generated rather
// than symlinked because Codex documents no symlink handling for plugins.
//
//   node dev/sync-us-plugin.mjs          rewrite plugins/gleap-us/
//   node dev/sync-us-plugin.mjs --check  exit 1 when plugins/gleap-us/ is stale
//
// Edit the root files, never plugins/gleap-us/ by hand.
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "plugins", "gleap-us");
const US_MCP_URL = "https://mcp.us.gleap.ai/mcp";
const SHARED_DIRS = ["skills", "hooks", "scripts"];

const readJson = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

const build = (out) => {
  for (const dir of SHARED_DIRS) cpSync(join(root, dir), join(out, dir), { recursive: true });

  const claude = readJson(".claude-plugin/plugin.json");
  mkdirSync(join(out, ".claude-plugin"), { recursive: true });
  writeFileSync(
    join(out, ".claude-plugin", "plugin.json"),
    json({
      ...claude,
      name: "gleap-us",
      displayName: "Gleap (US)",
      description: `${claude.description} For workspaces hosted in the US.`,
    }),
  );

  const codex = readJson(".codex-plugin/plugin.json");
  mkdirSync(join(out, ".codex-plugin"), { recursive: true });
  writeFileSync(
    join(out, ".codex-plugin", "plugin.json"),
    json({
      ...codex,
      name: "gleap-us",
      description: `${codex.description} For workspaces hosted in the US.`,
      interface: {
        ...codex.interface,
        displayName: "Gleap (US)",
        longDescription: codex.interface.longDescription.replace("(EU region)", "(US region)"),
      },
    }),
  );

  const mcp = readJson(".mcp.json");
  mcp.mcpServers.gleap.url = US_MCP_URL;
  writeFileSync(join(out, ".mcp.json"), json(mcp));

  // The directory lists this plugin on its own, so its README must stand alone.
  cpSync(join(root, ".claude-plugin", "icon.png"), join(out, ".claude-plugin", "icon.png"));
  writeFileSync(
    join(out, "README.md"),
    `# Gleap (US)

The Gleap plugin for workspaces hosted in Gleap's US region. It connects Claude Code and Codex to the US Gleap MCP server (${US_MCP_URL}) and adds the same skills and hooks as \`gleap\`: fix or answer a ticket as a tracked Gleap coding session (plan, screenshots and wrap-up show up in Gleap), draft a support reply, and triage the inbox.

## Install

\`\`\`bash
claude plugin marketplace add GleapSDK/gleap-claude-plugin
claude plugin install gleap-us@gleap
\`\`\`

On Claude Code 2.1.275 or later one line is enough:

\`\`\`
/plugin install gleap-us --marketplace GleapSDK/gleap-claude-plugin
\`\`\`

Sign in with your Gleap account when Claude asks. Workspaces in the EU region install \`gleap\` instead. Setup, hooks and Codex are covered in the README at the repository root.

This file is generated by \`dev/sync-us-plugin.mjs\`; edit the root files instead.
`,
  );
};

const listFiles = (dir) => {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p));
    }
  };
  if (existsSync(dir)) walk(dir);
  return out.sort();
};

const sameTree = (a, b) => {
  const fa = listFiles(a);
  const fb = listFiles(b);
  if (fa.join("\n") !== fb.join("\n")) return false;
  return fa.every((f) => readFileSync(join(a, f)).equals(readFileSync(join(b, f))));
};

const fresh = mkdtempSync(join(tmpdir(), "gleap-us-"));
try {
  build(fresh);
  if (process.argv.includes("--check")) {
    if (!sameTree(fresh, target)) {
      console.error("plugins/gleap-us is out of date. Run: node dev/sync-us-plugin.mjs");
      process.exit(1);
    }
    console.log("plugins/gleap-us is up to date");
  } else {
    rmSync(target, { recursive: true, force: true });
    mkdirSync(dirname(target), { recursive: true });
    cpSync(fresh, target, { recursive: true });
    console.log(`wrote ${relative(root, target)}/ (${listFiles(target).length} files)`);
  }
} finally {
  rmSync(fresh, { recursive: true, force: true });
}
